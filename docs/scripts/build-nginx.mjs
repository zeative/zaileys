// Writes the nginx config that serves the static export (docs-dist/) on a self-hosted box such as Dokploy.
// It mirrors what vercel.json does on Vercel: no trailing slashes, the docs.json redirects, the '/.md' rewrite,
// cache headers, and the custom 404 page.
// Usage: node docs/scripts/build-nginx.mjs <outFile>   (default: prints to stdout)
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const docsRedirects = JSON.parse(readFileSync(join(ROOT, 'docs', 'docs.json'), 'utf8')).redirects ?? []

const redirects = docsRedirects
  .map(({ source, destination, permanent }) => `  location = ${source} { return ${permanent === false ? 302 : 301} ${destination}; }`)
  .join('\n')

const conf = `# Generated by docs/scripts/build-nginx.mjs, do not edit by hand.
server {
  listen 80;
  server_name _;
  root /usr/share/nginx/html;

  # Redirects stay relative so they keep the scheme and host the visitor (or Cloudflare) used.
  absolute_redirect off;
  port_in_redirect off;
  charset utf-8;
  charset_types text/plain text/markdown text/css application/javascript application/json image/svg+xml;

  gzip on;
  gzip_vary on;
  gzip_min_length 1024;
  gzip_types text/plain text/markdown text/css application/javascript application/json image/svg+xml application/xml;

  error_page 404 /404.html;

  # docs.json redirects (a hosted-plan feature the static export doesn't ship).
${redirects}

  # Mintlify's page menu asks for path + '.md', which is '/.md' on the home page.
  location = /.md { default_type text/markdown; try_files /index.md =404; }

  location ~ \\.md$ {
    types { }
    default_type text/markdown;
    try_files $uri =404;
  }

  # Asset filenames carry a content hash, so they never go stale.
  location ~ ^/(_mintlify/assets|_next/static)/ {
    add_header Cache-Control "public, max-age=31536000, immutable";
    try_files $uri =404;
  }

  # The search index is rebuilt on every deploy; keep it short-lived.
  location = /search-index.json {
    add_header Cache-Control "public, max-age=600";
    try_files $uri =404;
  }

  location / {
    # Like vercel.json's trailingSlash: false.
    rewrite ^/(.+)/$ /$1 permanent;
    # no-transform stops Cloudflare's Email Address Obfuscation from rewriting JIDs such as 628…@s.whatsapp.net
    # inside the page's compiled MDX, which breaks client-side navigation (pages render empty).
    add_header Cache-Control "public, max-age=0, must-revalidate, no-transform";
    try_files $uri $uri.html $uri/index.html =404;
  }
}
`

const out = process.argv[2]
if (out) {
  writeFileSync(out, conf)
  console.log(`✓ nginx config written to ${out} (${docsRedirects.length} redirects)`)
} else {
  process.stdout.write(conf)
}
